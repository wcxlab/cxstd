//! Inject CommandQueue to reserve entities or defer changes until a command barrier.

use std::{cell::RefCell, collections::VecDeque, rc::Rc};

use super::{Component, EcsContext, Entity, EntityId, EntityRef, World};

type Command<C> = Box<dyn FnOnce(&mut World, &mut C, EcsContext<'_, C>) -> anyhow::Result<()>>;

/// A cloneable owner-thread queue for deferred entity and application changes.
pub struct CommandQueue<C = ()> {
    pending: Rc<RefCell<VecDeque<Command<C>>>>,
}

impl<C> Clone for CommandQueue<C> {
    fn clone(&self) -> Self {
        Self {
            pending: self.pending.clone(),
        }
    }
}

impl<C> Default for CommandQueue<C> {
    fn default() -> Self {
        Self {
            pending: Rc::default(),
        }
    }
}

impl<C> CommandQueue<C> {
    /// Queue work without retaining a borrow of the World.
    pub fn queue(&self, command: impl FnOnce(&mut World, &mut C) -> anyhow::Result<()> + 'static) {
        self.queue_with(move |world, host, _| command(world, host));
    }

    /// Queue work that also needs the executing Ecs's resources or facilities.
    pub fn queue_with(
        &self,
        command: impl FnOnce(&mut World, &mut C, EcsContext<'_, C>) -> anyhow::Result<()> + 'static,
    ) {
        self.pending.borrow_mut().push_back(Box::new(command));
    }

    pub fn len(&self) -> usize {
        self.pending.borrow().len()
    }

    pub fn is_empty(&self) -> bool {
        self.pending.borrow().is_empty()
    }

    /// Apply one batch in FIFO order. CommandQueue generated by that batch wait.
    /// If a command fails, earlier changes remain and unexecuted commands are
    /// retained ahead of newly queued work for a later explicit retry.
    pub fn apply(
        &self,
        world: &mut World,
        context: &mut C,
        access: EcsContext<'_, C>,
    ) -> anyhow::Result<usize> {
        let mut batch = std::mem::take(&mut *self.pending.borrow_mut());
        let mut applied = 0;
        while let Some(command) = batch.pop_front() {
            if let Err(error) = command(world, context, access) {
                let mut pending = self.pending.borrow_mut();
                batch.append(&mut pending);
                *pending = batch;
                return Err(error);
            }
            applied += 1;
        }
        Ok(applied)
    }
}

impl<C: 'static> CommandQueue<C> {
    pub fn add_entity(&self, entity: impl Into<Entity>) -> EntityId {
        let entity = entity.into();
        let id = EntityId::allocate();
        self.queue(move |world, _| {
            world.materialize_entity(id, entity);
            Ok(())
        });
        id
    }

    pub fn add_state<T: 'static>(&self, state: T) -> EntityRef<T> {
        let id = EntityId::allocate();
        self.queue(move |world, _| {
            world.materialize(id, Some(Box::new(state)));
            Ok(())
        });
        EntityRef::new(id)
    }

    pub fn add_component<T: Component>(&self, entity: EntityId, component: T) {
        self.queue(move |world, _| {
            world.entity_mut(entity)?.add_component(component);
            Ok(())
        });
    }

    pub fn remove<T: Component>(&self, entity: EntityId) {
        self.queue(move |world, _| {
            world.remove::<T>(entity)?;
            Ok(())
        });
    }

    pub fn despawn(&self, entity: EntityId) {
        self.queue(move |world, _| {
            world.despawn(entity);
            Ok(())
        });
    }
}

impl<C> CommandQueue<C> {
    pub(crate) fn clear(&self) {
        let pending = std::mem::take(&mut *self.pending.borrow_mut());
        drop(pending);
    }
}
